// Inlines the default assets as data URLs so the library works with zero
// configuration in every bundler (Vite dev pre-bundling breaks relative
// `new URL(..., import.meta.url)` references inside dependencies).
import { existsSync, readFileSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const assets = join(root, 'src/assets');
// artoolkit5-wasm only exports an `import` condition, so resolve it next to
// artoolkit5-ts (pnpm) or at the top level (npm hoisting).
const ts = realpathSync(join(root, 'node_modules/@ar-js-org/artoolkit5-ts'));
const wasmPath = [
  join(ts, '../artoolkit5-wasm/dist/artoolkit5.wasm'),
  join(ts, 'node_modules/@ar-js-org/artoolkit5-wasm/dist/artoolkit5.wasm'),
].find((p) => existsSync(p));
if (!wasmPath) throw new Error('artoolkit5.wasm not found');

const dataUrl = (file, mime) => `data:${mime};base64,${readFileSync(file).toString('base64')}`;
const header = '// Generated by scripts/generate-assets.mjs. Do not edit.\n';

writeFileSync(
  join(assets, 'inline.generated.ts'),
  header +
    `/** ARToolKit default camera calibration (640x480), from AR.js. */\n` +
    `export const CAMERA_PARAMETERS_URL: string = ${JSON.stringify(dataUrl(join(assets, 'camera_para.dat'), 'application/octet-stream'))};\n` +
    `/** The AR.js "Hiro" pattern marker. */\n` +
    `export const HIRO_PATTERN_URL: string = ${JSON.stringify(dataUrl(join(assets, 'patt.hiro'), 'text/plain'))};\n` +
    `/** The AR.js "Kanji" pattern marker. */\n` +
    `export const KANJI_PATTERN_URL: string = ${JSON.stringify(dataUrl(join(assets, 'patt.kanji'), 'text/plain'))};\n`,
);
writeFileSync(
  join(assets, 'wasm.generated.ts'),
  header +
    `/** The ARToolKit5 WebAssembly binary, loaded lazily when no \`wasmUrl\` is given. */\n` +
    `const WASM_URL: string = ${JSON.stringify(dataUrl(wasmPath, 'application/wasm'))};\nexport default WASM_URL;\n`,
);
console.log('assets generated');
